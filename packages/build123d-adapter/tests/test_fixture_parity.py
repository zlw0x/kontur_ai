IDS = [part.name.removesuffix(".v1_10.json") for part in PARTS]


@pytest.fixture(scope="module", params=PARTS, ids=IDS)
def built(request):
    """Each fixture, built once and measured by several tests.

    Module-scoped because a build is the expensive part and none of these tests
    mutate the solid. Any that did would be testing something other than parity.
    """
    parity: Parity = request.param
    return parity, build_part(parity.document())


def test_the_part_is_one_solid(built):
    parity, part = built
    assert len(part.solids()) == parity.bodies, parity.source


def test_the_faces_are_the_faces_kompas_reported(built):
    parity, part = built
    counted = collections.Counter(face.surface_type for face in read_faces(part))
    assert dict(counted) == parity.faces, parity.source


def test_the_bounding_box_is_the_drawing(built):
    parity, part = built
    box = part.bounding_box()
    measured = (float(box.size.X), float(box.size.Y), float(box.size.Z))
    for axis, (was, expected) in enumerate(zip(measured, parity.size_mm)):
        # Read off the solid, so no tessellation tolerance applies. A kernel that
        # cannot place a plane to a micron has a worse problem than this test.
        assert abs(was - expected) < 1e-6, f"axis {axis}: {was} != {expected}"


def test_the_volume_is_what_the_drawing_says(built):
    """The one measurement no face count can fake.

    A part can have every face of the right kind in the right place and still be
    the wrong solid — a cut applied to the wrong side, an island built as a boss.
    Volume is the check that notices.
    """
    parity, part = built
    assert float(part.volume) == pytest.approx(parity.volume_mm3, abs=1e-3)


def test_every_horizontal_face_has_the_area_it_had_on_kompas(built):
    parity, part = built
    areas: dict[float, float] = collections.defaultdict(float)
    for face in read_faces(part):
        if face.surface_type != "planar" or face.normal is None:
            continue
        if abs(abs(face.normal[2]) - 1.0) > 1e-9:
            continue
        areas[round(face.centroid[2], 3)] += face.area_mm2

    assert sorted(areas) == sorted(parity.horizontal_areas), parity.source
    for height, expected in parity.horizontal_areas.items():
        # A thousandth of a square millimetre: the precision the acceptance table
        # was written to, and finer than any modelling error could hide under.
        assert areas[height] == pytest.approx(expected, abs=1e-3), f"z = {height}"


def test_the_edges_are_counted_and_the_difference_is_the_seam(built):
    """Where the two kernels genuinely disagree, and why it is not a defect.

    A closed cylindrical face in OpenCascade is parameterised over a period, and
    the period has to start somewhere: the surface carries a seam edge along the
    line where its parameterisation wraps. KOMPAS's face has no such edge. So a
    through hole is three edges here and two there, and the totals differ by one
    per closed cylinder — not per cylindrical face, because the stadium plate's
    end caps are half cylinders and close nothing.

    Asserted rather than absorbed, because the difference is real and a selector
    written against edges will meet it. A seam is identifiable — it is the only
    edge of a solid that touches exactly one face — so a later operation can
    exclude it deliberately instead of being surprised by it.
    """
    parity, part = built
    edges = read_edges(part)
    assert len(edges) == parity.edges, parity.source

    seams = [edge for edge in edges if edge.adjacent_face_count == 1]
    assert len(seams) == parity.seam_edges
    assert all(edge.adjacent_surface_types == ("cylindrical",) for edge in seams)

    if parity.kompas_edges is not None:
        assert len(edges) - len(seams) == parity.kompas_edges, parity.source


def test_the_exported_files_verify(built, tmp_path_factory):
    """The whole worker path, not only the solid in memory.

    Built, written, reopened by a reader that did not write them, and measured
    against the document's own expectations (ENGINE-MIG-005). A parity run that
    stopped at the in-memory solid would prove nothing about the two files that
    are the product.
    """
    parity, _ = built
    document = parity.document()
    output = tmp_path_factory.mktemp(parity.name.replace(".", "-"))
    outcome = build(document, output)

    assert [artifact.kind for artifact in outcome.artifacts] == ["STEP", "STL"]
    report = verify(output / "model.step", output / "model.stl", Expectations.of(document))
    failed = [check for check in report.checks if not check.passed]
    assert report.valid, "; ".join(f"{check.name}: {check.detail}" for check in failed)
