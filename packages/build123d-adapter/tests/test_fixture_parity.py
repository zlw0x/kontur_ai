from cad_engine_build123d.topology import read_edges, read_faces  # noqa: E402
from cad_engine_build123d.verify import Expectations, verify  # noqa: E402

FIXTURES = Path(__file__).resolve().parents[3] / "tests" / "fixtures" / "cad-ir"


@dataclass(frozen=True)
class Parity:
    """One part, and everything the other engine — or arithmetic — says it is."""

    name: str
    #: Where these numbers come from. Not decoration: a parity figure whose
    #: source cannot be named is a figure somebody typed to make a test pass.
    source: str
    bodies: int
    #: Faces by surface type. The split matters more than the total — a part with
    #: the right face count and a plane where a cylinder belongs is a wrong part.
    faces: dict[str, int]
    edges: int
    volume_mm3: float
    size_mm: tuple[float, float, float]
    #: Area of each horizontal face, by the height it sits at. A face count says
    #: the topology is right; an area says the geometry is.
    horizontal_areas: dict[float, float] = field(default_factory=dict)
    #: How many of those edges are seams — one per *closed* cylinder. A half
    #: cylinder has no seam, so this is not the cylindrical face count.
    seam_edges: int = 0
    #: Edges KOMPAS reported for the same part, where an acceptance run recorded
    #: it. Absent where none did — the seam rule is then untestable here rather
    #: than assumed.
    kompas_edges: int | None = None

    def document(self):
        return validate_canonical(json.loads((FIXTURES / self.name).read_text("utf-8")))


