"""build123d builds the same parts KOMPAS built.

ENGINE-MIG-006. The migration's premise is that the engine underneath CAD-IR can
be replaced without changing what a customer gets, and that premise is only worth
anything if it is checked. So every fixture the KOMPAS engine was accepted on is
built again here and measured against the numbers that acceptance recorded.

Two rules make this a parity test rather than a self-consistency one.

*The expected numbers are not computed from the build.* They are transcribed from
`docs/acceptance/` — what KOMPAS measured — or derived by arithmetic from the
drawing. A table generated by the engine under test would agree with it about
anything it got wrong, which is the same argument ADR-018 makes about
expectations and the one `verify.py` makes about reading a mesh back as a file.

*A difference is stated, not tolerated.* The two kernels do not model topology
identically, and the one place they disagree — the seam edge OpenCascade carries
on a closed cylindrical face — is written down as a rule with its own test rather
than hidden inside a fudged edge count.

These need the CAD library, so they skip where it is absent. That keeps the suite
runnable on a machine with no engine at all, which is the property ENGINE-MIG-002
set up; CI runs them in the job that installs the worker's own requirements.
"""

from __future__ import annotations

import collections
import json
from dataclasses import dataclass, field
from pathlib import Path

